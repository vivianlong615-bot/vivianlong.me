window.PORTFOLIO_LANG_KEY = 'portfolio-lang';

window.readPortfolioLang = function () {
  try {
    const stored = localStorage.getItem(window.PORTFOLIO_LANG_KEY);
    return stored === 'en' || stored === 'zh' ? stored : 'zh';
  } catch {
    return 'zh';
  }
};

window.writePortfolioLang = function (lang) {
  try {
    localStorage.setItem(window.PORTFOLIO_LANG_KEY, lang);
  } catch { /* ignore */ }
};
